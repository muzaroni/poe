import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/lib/gem-links.ts', import.meta.url), 'utf8');
const context = { exports: {}, require: name => {
  if (name === './gem-rewards') return { gemRewardNpc: () => null };
  throw new Error(`Unexpected import: ${name}`);
} };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText, context);
const { compareGemSetups, setupRows } = context.exports;
const gem = (name, color = 'red') => ({ type: 'gem', attrs: { name, color } });
const text = value => ({ type: 'text', text: value });
const row = (label, ...content) => ({ type: 'paragraph', content: [text(`${label}: `), ...content] });
const { gemAcquisitionGroups } = context.exports;
const purchase = (name, first) => ({ type: 'gem', attrs: { name, color: 'blue', acquisition: 'buy', acquisitionAct: 1, acquisitionFirst: first } });
const grouped = gemAcquisitionGroups([row('Main', purchase('Kinetic Fusillade', true), text(' + '), purchase('Volley', true)), row('Main 2', purchase('Kinetic Fusillade', false), text(' + '), purchase('Volley', false))]);
assert.deepEqual(Array.from(grouped.buy, ({ name, quantity }) => [name, quantity]), [['Kinetic Fusillade', 2], ['Volley', 2]], 'Repeated purchases in separate links should be grouped by gem');
const main = row('Main', gem('Sunder'), text(' + '), gem('Ruthless Support'));
const next = row('Main', gem('Sunder'), text(' + '), gem('Melee Physical Damage Support'));
let changes = compareGemSetups([next], [main]);
assert.equal(changes.length, 1);
assert.equal(changes[0].removed[0].name, 'Ruthless Support');
assert.equal(changes[0].added[0].name, 'Melee Physical Damage Support');
assert.equal(compareGemSetups([main], [main]).length, 0);
assert.equal(compareGemSetups([main, row('Movement', gem('Leap Slam'))], [main])[0].added[0].name, 'Leap Slam');
assert.equal(compareGemSetups([main], [main, row('Utility', gem('Blood Rage', 'green'))])[0].removed[0].name, 'Blood Rage');
const independent = row('Utility', gem('Frostblink', 'blue'), text(', '), gem('Flame Dash', 'blue'));
const linked = row('Utility', gem('Frostblink', 'blue'), text(' + '), gem('Flame Dash', 'blue'));
assert.equal(compareGemSetups([linked], [independent])[0].linksChanged, true);
const reordered = row('Utility', gem('Flame Dash', 'blue'), text(', '), gem('Frostblink', 'blue'));
assert.equal(compareGemSetups([reordered], [independent]).length, 0, 'Reordering independent gems is not a link change');
const level1 = row('Main', gem('Sunder'), text(' (1) + '), gem('Ruthless Support'));
changes = compareGemSetups([level1], [main]);
assert.equal(changes[0].added[0].annotation, '(1)');
assert.equal(changes[0].removed[0].name, 'Sunder');
const repeated = row('Utility', gem('Momentum Support', 'green'), text(', '), gem('Momentum Support', 'green'));
assert.equal(compareGemSetups([repeated], [row('Utility', gem('Momentum Support', 'green'))])[0].added.length, 1, 'Count duplicate gems separately');
const checklist = [{ type: 'taskList', content: [{ type: 'taskItem', attrs: { checked: false }, content: [main] }] }];
assert.equal(setupRows(checklist)[0].gems.length, 2);
assert.equal(compareGemSetups([row('MAIN', gem('Sunder'), text(' + '), gem('Ruthless Support'))], [main]).length, 0, 'Labels match regardless of case');
const savedBefore = JSON.stringify([main]);
compareGemSetups([next], [main]);
assert.equal(JSON.stringify([main]), savedBefore, 'Comparison must not mutate earlier content');
assert.equal(compareGemSetups([next], JSON.parse(JSON.stringify([main])))[0].added[0].name, 'Melee Physical Damage Support');
console.log('Gem link checks passed: replacement, additions, removals, linking, annotations, duplicates, checklists, stable labels, and immutable saved comparisons.');

const { inlineGemChanges } = context.exports;
let inline = inlineGemChanges([next], [main]);
assert.equal(inline.rows.get(next).gems[0].added, undefined, 'Unchanged gems must have no added indicator');
assert.equal(inline.rows.get(next).gems[1].replaces.name, 'Ruthless Support');
assert.equal(inline.rows.get(next).removed.length, 0, 'Replacement hints should not duplicate removals');
const add = row('Main', gem('Sunder'), text(' + '), gem('Ruthless Support'), text(' + '), gem('Added Fire Damage Support'));
assert.equal(inlineGemChanges([add], [main]).rows.get(add).gems[2].added, true);
const remove = row('Main', gem('Sunder'));
assert.equal(inlineGemChanges([remove], [main]).rows.get(remove).removed[0].name, 'Ruthless Support');
assert.equal(inlineGemChanges([], [main]).removedSetups[0].title, 'Main', 'Entirely removed setups must remain visible');
assert.equal(inlineGemChanges([linked], [independent]).rows.get(linked).linksChanged, true);
assert.equal(inlineGemChanges([level1], [main]).rows.get(level1).gems[0].replaces.name, 'Sunder');
assert.equal(inlineGemChanges([repeated], [row('Utility', gem('Momentum Support', 'green'))]).rows.get(repeated).gems.filter(hint => hint.added).length, 1);
const duplicateLabels = [main, next];
assert.equal(inlineGemChanges(duplicateLabels, [main, main]).rows.get(next).gems[1].replaces.name, 'Ruthless Support');
console.log('Inline hint checks passed: additions, replacements, removals, removed setups, linking, annotations, duplicates, and unchanged rows.');

const beforeMove = [row('Utility', gem('Frostblink', 'blue'), text(', '), gem('Blood Rage', 'green')), row('Movement', gem('Leap Slam'))];
const afterMove = [row('Utility', gem('Blood Rage', 'green')), row('Movement', gem('Leap Slam'), text(', '), gem('Frostblink', 'blue'))];
const movement = inlineGemChanges(afterMove, beforeMove);
assert.equal(movement.rows.get(afterMove[1]).gems[1].movedFrom, 'Utility');
assert.equal(movement.rows.get(afterMove[1]).gems[1].added, undefined, 'A moved gem must not be NEW');
assert.equal(movement.rows.get(afterMove[0]).removed.length, 0, 'A moved gem must not be REMOVED');
assert.equal(movement.rows.get(afterMove[0]).movedOut[0].to, 'Movement');
assert.equal(movement.rows.get(afterMove[0]).linksChanged, false, 'A move should not duplicate a linking-change hint');
const copied = [row('Utility', gem('Frostblink', 'blue')), row('Movement', gem('Frostblink', 'blue'))];
assert.equal(inlineGemChanges(copied, [copied[0]]).rows.get(copied[1]).gems[0].added, true, 'Adding a second copy is NEW, not a move');
const onlyDestination = [row('Movement', gem('Frostblink', 'blue'))];
const wholeGroupMove = inlineGemChanges(onlyDestination, [row('Utility', gem('Frostblink', 'blue'))]);
assert.equal(wholeGroupMove.removedSetups[0].gems.length, 0);
assert.equal(wholeGroupMove.removedSetups[0].movedOut[0].to, 'Movement');
const exchangeBefore = [row('Main', gem('Fireball', 'blue')), row('Utility', gem('Frostblink', 'blue'))];
const exchangeAfter = [row('Main', gem('Frostblink', 'blue')), row('Utility', gem('Fireball', 'blue'))];
const exchange = inlineGemChanges(exchangeAfter, exchangeBefore);
assert.equal(exchange.rows.get(exchangeAfter[0]).gems[0].movedFrom, 'Utility');
assert.equal(exchange.rows.get(exchangeAfter[1]).gems[0].movedFrom, 'Main');
assert.equal(exchange.rows.get(exchangeAfter[0]).gems[0].replaces, undefined, 'Moves must be matched before replacements');
const severalBefore = [row('A', gem('Faster Attacks Support', 'green'), text(', '), gem('Faster Attacks Support', 'green'))];
const severalAfter = [row('A', gem('Faster Attacks Support', 'green')), row('B', gem('Faster Attacks Support', 'green'))];
const duplicateMove = inlineGemChanges(severalAfter, severalBefore);
assert.equal(duplicateMove.rows.get(severalAfter[0]).gems[0].movedFrom, undefined);
assert.equal(duplicateMove.rows.get(severalAfter[1]).gems[0].movedFrom, 'A');
assert.equal(duplicateMove.rows.get(severalAfter[0]).movedOut.length, 1);
assert.equal(inlineGemChanges(JSON.parse(JSON.stringify(afterMove)), JSON.parse(JSON.stringify(beforeMove))).rows.size, 2);
console.log('Move checks passed: both directions, duplicate counts, new copies, removed groups, exchanges, and move-before-swap matching.');

const { setupGemReferences } = context.exports;
const ref = (content, index) => setupGemReferences(content)[index].ref;
const newOverride = { current: { [ref([next], 1)]: { kind: 'new' } } };
const separate = inlineGemChanges([next], [main], newOverride).rows.get(next);
assert.equal(separate.gems[1].added, true);
assert.equal(separate.gems[1].replaces, undefined);
assert.equal(separate.removed[0].name, 'Ruthless Support', 'Explicit NEW must keep the old gem as a separate removal');
const twoOld = row('Main', gem('Sunder'), text(' + '), gem('Ruthless Support'), text(' + '), gem('Maim Support'));
const precise = { current: { [ref([next], 1)]: { kind: 'swap', from: ref([twoOld], 2) } } };
const exactSwap = inlineGemChanges([next], [twoOld], precise).rows.get(next);
assert.equal(exactSwap.gems[1].replaces.name, 'Maim Support');
assert.equal(exactSwap.removed[0].name, 'Ruthless Support');
const hiddenRemoval = { ...newOverride, removed: { [ref([main], 1)]: 'hide' } };
assert.equal(inlineGemChanges([next], [main], hiddenRemoval).rows.get(next).removed.length, 0);
const noBadge = { current: { [ref([next], 1)]: { kind: 'none' } } };
assert.equal(JSON.stringify(inlineGemChanges([next], [main], noBadge).rows.get(next).gems[1]), '{}');
const movedChoice = { current: { [ref(afterMove, 2)]: { kind: 'moved', from: ref(beforeMove, 0) } } };
assert.equal(inlineGemChanges(afterMove, beforeMove, movedChoice).rows.get(afterMove[1]).gems[1].movedFrom, 'Utility');
const newInsteadOfMove = { current: { [ref(afterMove, 2)]: { kind: 'new' } } };
const deliberateCopy = inlineGemChanges(afterMove, beforeMove, newInsteadOfMove);
assert.equal(deliberateCopy.rows.get(afterMove[1]).gems[1].added, true);
assert.equal(deliberateCopy.rows.get(afterMove[0]).removed[0].name, 'Frostblink');
const savedChoice = JSON.parse(JSON.stringify(precise));
assert.equal(inlineGemChanges([next], [twoOld], savedChoice).rows.get(next).gems[1].replaces.name, 'Maim Support');
assert.equal(ref([next], 1), ref([row('Main', gem('Melee Physical Damage Support'), text(' + '), gem('Sunder'))], 0), 'Overrides must survive reordering different gems');
const absentSource = { current: { [ref([next], 1)]: { kind: 'swap', from: 'missing' } } };
assert.equal(inlineGemChanges([next], [main], absentSource).rows.get(next).gems[1].replaces.name, 'Ruthless Support', 'Missing sources fall back to automatic');
assert.equal(inlineGemChanges([next], [main], null).rows.get(next).gems[1].replaces.name, 'Ruthless Support', 'Reset restores automatic comparison');
assert.equal(JSON.stringify(precise), JSON.stringify(savedChoice), 'Rendering must not mutate saved manual choices');
console.log('Manual badge checks passed: separate NEW/REMOVED, exact swaps, moved overrides, hidden removals, no badge, reorder stability, saved choices, and automatic fallback.');

const { gemLinkGroups, gemSocketOptions } = context.exports;
const choiceRow = (...choices) => row('Main', gem('Sunder'), text(' + '), gem('Melee Physical Damage Support'), text(' + '), ...choices);
const singleChoice = choiceRow(gem('Ruthless Support'));
const eitherChoice = choiceRow(gem('Ruthless Support'), text(' or '), gem('Close Combat Support', 'green'));
const reverseChoice = choiceRow(gem('Close Combat Support', 'green'), text(' OR '), gem('Ruthless Support'));
assert.equal(gemLinkGroups(eitherChoice).groups[0].length, 3, 'Alternatives occupy one socket in a 3-link');
assert.equal(gemSocketOptions(gemLinkGroups(eitherChoice).groups[0][2]).length, 2);
assert.equal(setupRows([eitherChoice])[0].gems[2].annotation, '');
assert.equal(setupRows([eitherChoice])[0].gems[3].annotation, '');
assert.equal(compareGemSetups([reverseChoice], [eitherChoice]).length, 0, 'Reordering alternatives is unchanged');
assert.equal(inlineGemChanges([reverseChoice], [eitherChoice]).rows.get(reverseChoice).linksChanged, false);
let altChanges = inlineGemChanges([eitherChoice], [singleChoice]).rows.get(eitherChoice);
assert.equal(altChanges.gems[2].replaces, undefined);
assert.equal(altChanges.gems[3].added, true, 'Only the new alternative gets NEW');
altChanges = inlineGemChanges([singleChoice], [eitherChoice]).rows.get(singleChoice);
assert.equal(altChanges.removed[0].name, 'Close Combat Support');
const replacedChoice = choiceRow(gem('Ruthless Support'), text(' or '), gem('Maim Support'));
assert.equal(inlineGemChanges([replacedChoice], [eitherChoice]).rows.get(replacedChoice).gems[3].replaces.name, 'Close Combat Support');
const annotatedChoice = choiceRow(gem('Ruthless Support'), text(' (1) or '), gem('Close Combat Support', 'green'), text(' (2)'));
assert.equal(setupRows([annotatedChoice])[0].gems[2].annotation, '(1)');
assert.equal(setupRows([annotatedChoice])[0].gems[3].annotation, '(2)');
assert.equal(gemLinkGroups(JSON.parse(JSON.stringify(eitherChoice))).groups[0].length, 3);
console.log('Alternative checks passed: shared sockets, option order, separate annotations, additions, removals, replacements, and saved content.');

const { gemProgressionStages } = context.exports;
const heading = title => ({ type: 'heading', attrs: { level: 3 }, content: [text(title)] });
const link1 = row('Link 1', gem('Ground Slam'), text(' + '), gem('Ruthless Support'));
const link2 = row('Link 2', gem('Shield Charge'), text(' + '), gem('Momentum Support', 'green'));
const utility = row('Util', gem('Frostblink', 'blue'));
const leap = row('Link 2', gem('Leap Slam'), text(' + '), gem('Momentum Support', 'green'));
const sunder = row('Link 1', gem('Sunder'), text(' + '), gem('Ruthless Support'));
const faster = row('Link 2', gem('Leap Slam'), text(' + '), gem('Faster Attacks Support', 'green'), text(' + '), gem('Momentum Support', 'green'));
const stagesContent = [heading('Level 1–9'), link1, link2, utility, heading('Level 10'), leap, heading('Level 12'), sunder, faster, utility];
let stages = gemProgressionStages(stagesContent);
assert.equal(stages.length, 3);
assert.equal(stages[0].changes, null, 'Starting stage has no badges');
assert.equal(stages[1].changes.rows.get(leap).gems[0].replaces.name, 'Shield Charge');
assert.equal(stages[1].changes.removedSetups.length, 0, 'Omitted links are unchanged');
assert.equal(stages[2].changes.rows.get(sunder).gems[0].replaces.name, 'Ground Slam');
assert.equal(stages[2].changes.rows.get(faster).gems[0].replaces, undefined, 'Leap Slam was already introduced in level 10');
assert.equal(stages[2].changes.rows.get(faster).gems[1].added, true);
assert.equal(stages[2].changes.rows.get(faster).gems[2].added, undefined);
assert.equal(stages[2].changes.rows.get(utility).gems[0].added, undefined);
const stageRef = context.exports.setupGemReferences([leap])[0].ref;
stages = gemProgressionStages(stagesContent, null, { stages: { 'level 10:0': { current: { [stageRef]: { kind: 'new' } } } } });
assert.equal(stages[1].changes.rows.get(leap).gems[0].added, true);
assert.equal(stages[2].changes.rows.get(faster).gems[0].added, undefined, 'Manual choices only affect their stage');
const nextAct = gemProgressionStages([faster, sunder, utility], { title: 'Earlier act', content: stagesContent });
assert.equal(nextAct[0].changes.rows.get(faster).gems.some(hint => hint.added || hint.replaces), false, 'External comparison uses the final cumulative links');
const noHeading = gemProgressionStages([next], { title: 'Earlier act', content: [main] });
assert.equal(noHeading[0].changes.rows.get(next).gems[1].replaces.name, 'Ruthless Support');
console.log('Stage checks passed: partial updates, cumulative links, additions, replacements, scoped manual choices, and next-act continuation.');
